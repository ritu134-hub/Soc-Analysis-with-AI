@app.route('/api/stream/events')
def api_stream_events():
    """SSE endpoint for streaming live events & logs to dashboard."""
    def event_stream():
        q = queue.Queue()

        def listener_callback(event_data, log_data):
            q.put({"event": event_data, "log": log_data})

        register_listener(listener_callback)
        try:
            yield "data: {\"type\": \"connected\"}\n\n"
            while True:
                try:
                    data = q.get(timeout=25)
                    metrics = get_soc_metrics()
                    payload = {
                        "type": "update",
                        "metrics": metrics,
                        "event": data.get("event"),
                        "log": data.get("log")
                    }
                    yield f"data: {json.dumps(payload)}\n\n"
                except queue.Empty:
                    # Heartbeat
                    yield "data: {\"type\": \"ping\"}\n\n"
        finally:
            unregister_listener(listener_callback)

    return Response(event_stream(), mimetype='text/event-stream')

