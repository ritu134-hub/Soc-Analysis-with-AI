@app.route('/api/reports/<report_id>/pdf', methods=['GET'])
def api_download_report_pdf(report_id):
    report = get_report_by_id(report_id)
    if not report:
        return jsonify({"error": "Report not found"}), 404

    pdf = FPDF()
    pdf.add_page()
    pdf.set_auto_page_break(auto=True, margin=15)
    
    # Title Header
    pdf.set_font("Helvetica", "B", 18)
    pdf.set_text_color(220, 38, 38) # Red header
    pdf.cell(0, 10, "SECURITY INCIDENT ANALYSIS REPORT", ln=True, align="C")
    
    pdf.set_font("Helvetica", "I", 10)
    pdf.set_text_color(100, 100, 100)
    pdf.cell(0, 6, f"Generated by Groq SOC AI Analyst | Report ID: {report['report_id']}", ln=True, align="C")
    pdf.ln(5)

    # Metadata Table
    pdf.set_font("Helvetica", "B", 10)
    pdf.set_text_color(0, 0, 0)
    pdf.set_fill_color(240, 240, 240)
    
    pdf.cell(45, 7, " Event Title:", border=1, fill=True)
    pdf.set_font("Helvetica", "", 10)
    pdf.cell(145, 7, f" {report.get('event_title', 'N/A')}", border=1, ln=True)
    
    pdf.set_font("Helvetica", "B", 10)
    pdf.cell(45, 7, " Severity / Category:", border=1, fill=True)
    pdf.set_font("Helvetica", "", 10)
    pdf.cell(145, 7, f" {report.get('event_severity', 'N/A')} | {report.get('event_category', 'N/A')}", border=1, ln=True)

    pdf.set_font("Helvetica", "B", 10)
    pdf.cell(45, 7, " Source IP / Date:", border=1, fill=True)
    pdf.set_font("Helvetica", "", 10)
    pdf.cell(145, 7, f" {report.get('source_ip', 'N/A')} | {report['created_at']}", border=1, ln=True)

    pdf.set_font("Helvetica", "B", 10)
    pdf.cell(45, 7, " MITRE ATT&CK Tag:", border=1, fill=True)
    pdf.set_font("Helvetica", "", 10)
    pdf.cell(145, 7, f" {report.get('mitre_attack', 'N/A')}", border=1, ln=True)
    pdf.ln(8)

    # Report Body Markdown Cleanup
    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(30, 30, 30)
    
    lines = report['content_markdown'].split('\n')
    for line in lines:
        line_clean = line.encode('latin-1', 'replace').decode('latin-1')
        if line_clean.startswith('# '):
            pdf.set_font("Helvetica", "B", 14)
            pdf.set_text_color(15, 23, 42)
            pdf.cell(0, 8, line_clean.replace('# ', '').strip(), ln=True)
        elif line_clean.startswith('## '):
            pdf.set_font("Helvetica", "B", 12)
            pdf.set_text_color(30, 58, 138)
            pdf.cell(0, 7, line_clean.replace('## ', '').strip(), ln=True)
        elif line_clean.startswith('### '):
            pdf.set_font("Helvetica", "B", 11)
            pdf.set_text_color(51, 65, 85)
            pdf.cell(0, 6, line_clean.replace('### ', '').strip(), ln=True)
        elif line_clean.startswith('- ') or line_clean.startswith('* '):
            pdf.set_font("Helvetica", "", 10)
            pdf.multi_cell(0, 5, "  * " + line_clean[2:].strip())
        else:
            pdf.set_font("Helvetica", "", 10)
            if line_clean.strip():
                pdf.multi_cell(0, 5, line_clean.strip())
            else:
                pdf.ln(3)

    response = make_response(bytes(pdf.output()))
    response.headers['Content-Type'] = 'application/pdf'
    response.headers['Content-Disposition'] = f'attachment; filename="SOC_Report_{report["report_id"]}.pdf"'
    return response

